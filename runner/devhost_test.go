package runner

import "testing"

func TestFormatReal(t *testing.T) {
	tests := []struct {
		v           float64
		width, prec int32
		want        string
	}{
		{1.5, -1, -1, " 1.5000000000E+00"},
		{-1.5, -1, -1, "-1.5000000000E+00"},
		{0, -1, -1, " 0.0000000000E+00"},
		{123456789, -1, -1, " 1.2345678900E+08"},
		{9.99999999999, -1, -1, " 1.0000000000E+01"},
		{1234.5678, 12, -1, " 1.23457E+03"},
		{1.5e-5, 10, -1, " 1.500E-05"},
		{1e100, -1, -1, " 1.0000000000E+100"},
		{1.5, 1, -1, " 1.5E+00"},
		{1.5, 8, 2, "    1.50"},
		{2.5, 0, 0, "3"},
		{-2.5, 0, 0, "-3"},
		{0.125, 0, 2, "0.13"},
		{1.005, 0, 2, "1.00"}, // exakt 1.00499999...
		{0.001, 0, 2, "0.00"},
		{-0.001, 0, 2, "0.00"},
		{999.996, 0, 2, "1000.00"},
		{0.05, 0, 1, "0.1"},
		{12345.678, 0, 0, "12346"},
		{0.0001234, 0, 6, "0.000123"},
	}
	for _, tt := range tests {
		if got := formatReal(tt.v, tt.width, tt.prec); got != tt.want {
			t.Errorf("formatReal(%v, %d, %d) = %q, want %q", tt.v, tt.width, tt.prec, got, tt.want)
		}
	}
}
